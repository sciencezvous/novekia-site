type BranchQuestionInput = Omit<QuestionInput, 'path' | 'condition'> & {
  category: string
}

function branchQuestion(input: BranchQuestionInput): ConciergeQuestion {
  const { category, ...question } = input
  return defineQuestion({
    ...question,
    path: 'solutions',
    condition: categoryCondition(category),
  })
}

