type QuestionInput = Omit<
  ConciergeQuestion,
  'kind' | 'allowsFreeText' | 'sensitiveData'
> &
  Partial<Pick<ConciergeQuestion, 'allowsFreeText' | 'sensitiveData'>>

function defineQuestion(input: QuestionInput): ConciergeQuestion {
  return {
    kind: 'question',
    allowsFreeText: false,
    sensitiveData: false,
    ...input,
  }
}

function defineSystemStep(
  input: Omit<ConciergeSystemStep, 'kind'>,
): ConciergeSystemStep {
  return { kind: 'system', ...input }
}

function options(values: readonly string[]): readonly ConciergeQuestionOption[] {
  return values.map((value) => ({ value, label: value }))
}

function categoryCondition(value: string): ConciergeCondition {
  return {
    questionId: 'solutions.need_category',
    operator: 'equals',
    value,
  }
}

