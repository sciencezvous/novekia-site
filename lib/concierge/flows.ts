export function getFlowByPath(
  path: ConciergePath,
  definition: ConciergeDefinition = conciergeDefinition,
): ConciergeFlowDefinition | undefined {
  return definition.flows.find((flow) => flow.path === path)
}

export function getAllStepsForFlow(
  flow: ConciergeFlowDefinition,
  definition: ConciergeDefinition = conciergeDefinition,
): readonly ConciergeStep[] {
  return [...flow.steps, ...definition.sharedSteps]
}

export function getStepById(
  flow: ConciergeFlowDefinition,
  stepId: string,
  definition: ConciergeDefinition = conciergeDefinition,
): ConciergeStep | undefined {
  return getAllStepsForFlow(flow, definition).find((step) => step.id === stepId)
}
